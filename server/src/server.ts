import 'dotenv/config';
import express from 'express';
 import cors from 'cors';
 import helmet from 'helmet';
 import rateLimit from 'express-rate-limit';
 import { ZodError } from 'zod';
 import api from './routes/api';
 import {notFound,errors} from './middleware/errors';
if(!process.env.DATABASE_URL||!process.env.JWT_SECRET) console.warn('DATABASE_URL and JWT_SECRET must be set in server/.env');
const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_URL||'http://localhost:5173'}));
app.use(express.json({limit:'30kb'}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(_req,res)=>res.json({ok:true}));
app.use('/api',api);
app.use(notFound);
app.use((err:Error,_req:express.Request,res:express.Response,next:express.NextFunction)=>{if(err instanceof ZodError)return res.status(400).json({message:'Please check the information you entered.',errors:err.flatten().fieldErrors});next(err)});
app.use(errors);
const port=Number(process.env.PORT)||4000;
app.listen(port,()=>console.log(`Mindful Hub API listening on ${port}`));
